// Downloads glyph subsets of the OFL fonts used by V3CT0R from the Google Fonts
// CSS API (`text=` subsetting) and writes them to src/assets/fonts/ + a generated fonts.css.
// Run once at dev time (needs network): `npm run fonts`. The output is committed, so the
// app itself never touches the network.
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'src', 'assets', 'fonts');
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36';

const range = (a, b) => Array.from({ length: b - a + 1 }, (_, i) => String.fromCodePoint(a + i)).join('');

const LATIN = range(0x20, 0x7e) + range(0xa0, 0xff) + 'ŒœŸ';
const MONO_CHARS =
  LATIN +
  range(0x391, 0x3a9) + range(0x3b1, 0x3c9) + 'ϕϑϵ' +
  '–—‘’“”«»…•′″‰‖' +
  range(0x2070, 0x209c) +
  'ℝℕℤℚℂℵ' +
  range(0x2190, 0x21ff) +
  range(0x2200, 0x22ff) +
  '⌀⌘⏎' +
  range(0x2500, 0x259f) +
  range(0x25a0, 0x25ff) +
  '⚠✕✓✦★';
const DISPLAY_CHARS = LATIN + '’–—…·▸/';
const KANJI_CHARS =
  '数学無限次元積分形定原理空間幾何解析時微極素虚円周率黄金比位相対称変換関証明公式収束発散連続集合写像実複系統計算自己似超立方体群環場確偶然分布繊維';

const JOBS = [
  { family: 'JetBrains Mono', weights: [400, 500, 700], text: MONO_CHARS, file: 'jbmono' },
  { family: 'Michroma', weights: [400], text: DISPLAY_CHARS, file: 'michroma' },
  { family: 'Noto Sans JP', weights: [400], text: KANJI_CHARS, file: 'kanji', as: 'VM Kanji' },
];

function chunks(str, n) {
  const cps = [...new Set([...str])];
  const out = [];
  for (let i = 0; i < cps.length; i += n) out.push(cps.slice(i, i + n).join(''));
  return out;
}

async function get(url, binary) {
  const res = await fetch(url, { headers: { 'User-Agent': UA } });
  if (!res.ok) throw new Error(`${res.status} ${url}`);
  return binary ? Buffer.from(await res.arrayBuffer()) : res.text();
}

await mkdir(outDir, { recursive: true });
let css = '/* Generated by scripts/fetch-fonts.mjs — do not edit. Fonts under SIL OFL 1.1 (see LICENSES.md). */\n';
let total = 0;
for (const job of JOBS) {
  for (const w of job.weights) {
    const parts = chunks(job.text, 120);
    for (let p = 0; p < parts.length; p++) {
      const fam = job.family.replace(/ /g, '+');
      const url = `https://fonts.googleapis.com/css2?family=${fam}:wght@${w}&text=${encodeURIComponent(parts[p])}`;
      const sheet = await get(url);
      const faces = [...sheet.matchAll(/src: url\(([^)]+)\) format\('woff2'\);\s*unicode-range: ([^;]+);/g)];
      for (let k = 0; k < faces.length; k++) {
        const [, src, ur] = faces[k];
        const name = `${job.file}-${w}-${p}${faces.length > 1 ? '-' + k : ''}.woff2`;
        const buf = await get(src, true);
        total += buf.length;
        await writeFile(join(outDir, name), buf);
        css += `@font-face{font-family:'${job.as ?? job.family}';font-style:normal;font-weight:${w};font-display:block;src:url('./${name}') format('woff2');unicode-range:${ur};}\n`;
      }
    }
  }
}
await writeFile(join(outDir, 'fonts.css'), css);

const ofl = await get('https://raw.githubusercontent.com/JetBrains/JetBrainsMono/master/OFL.txt');
await writeFile(join(outDir, 'OFL.txt'), ofl);
console.log(`fonts: ${(total / 1024).toFixed(1)} KiB written to src/assets/fonts`);
