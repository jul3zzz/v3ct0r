// Computes 10 000 decimals of π, e, φ, √2, ln 2, ζ(3) and γ with BigInt fixed-point arithmetic,
// cross-checks each constant with a second independent formula, and writes src/data/digits.ts.
//   node scripts/gen-digits.mjs [digits]
import { writeFile, mkdir } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const D = Number(process.argv[2] ?? 10000);
const G = 30; // guard digits
const P = D + G;
const S = 10n ** BigInt(P);

const t0 = Date.now();
const log = (m) => console.log(`[${((Date.now() - t0) / 1000).toFixed(1)}s] ${m}`);

function atanInv(x) {
  // arctan(1/x) * S
  const x2 = BigInt(x) * BigInt(x);
  let term = S / BigInt(x);
  let sum = term;
  for (let k = 1n; term !== 0n; k++) {
    term /= x2;
    const t = term / (2n * k + 1n);
    sum += k % 2n ? -t : t;
  }
  return sum;
}
function atanhInv(x) {
  const x2 = BigInt(x) * BigInt(x);
  let term = S / BigInt(x);
  let sum = term;
  for (let k = 1n; term !== 0n; k++) {
    term /= x2;
    sum += term / (2n * k + 1n);
  }
  return sum;
}
function isqrt(n) {
  if (n < 2n) return n;
  let x = BigInt(Math.floor(Math.sqrt(Number(n >> BigInt(Math.max(0, n.toString(2).length - 100))))) ) << BigInt(Math.floor(Math.max(0, n.toString(2).length - 100) / 2));
  if (x === 0n) x = 1n;
  for (;;) {
    const y = (x + n / x) >> 1n;
    if (y >= x && y - x <= 1n) {
      let r = x < y ? x : y;
      while (r * r > n) r--;
      while ((r + 1n) * (r + 1n) <= n) r++;
      return r;
    }
    x = y;
  }
}
function toStr(v) {
  // v is scaled by S; keep D decimals (truncate)
  const s = v.toString();
  const intLen = s.length - P;
  const ip = intLen > 0 ? s.slice(0, intLen) : '0';
  const frac = (intLen > 0 ? s.slice(intLen) : s.padStart(P, '0')).slice(0, D);
  return `${ip}.${frac}`;
}
function agree(a, b, name) {
  const sa = toStr(a);
  const sb = toStr(b);
  // allow the last couple of digits to differ only if a carry boundary; require D-2 equal
  let i = 0;
  while (i < sa.length && sa[i] === sb[i]) i++;
  const ok = i >= sa.length - 2;
  log(`${name}: ${ok ? 'OK' : 'MISMATCH'} (agree on ${i - 2} decimals)`);
  if (!ok) process.exit(1);
  return sa;
}

// π — Machin vs Takano
const pi1 = 16n * atanInv(5) - 4n * atanInv(239);
const pi2 = 48n * atanInv(49) + 128n * atanInv(57) - 20n * atanInv(239) + 48n * atanInv(110443);
const PI = agree(pi1, pi2, 'pi');

// e — Σ 1/k! vs Σ (2k+2)/(2k+1)!
let e1 = 0n;
{
  let term = S;
  for (let k = 1n; term !== 0n; k++) {
    e1 += term;
    term /= k;
  }
}
let e2 = 0n;
{
  // term_k = 1/(2k+1)! ; sum (2k+2) * term_k
  let fact = S; // 1/1!
  for (let k = 0n; fact !== 0n; k++) {
    e2 += (2n * k + 2n) * fact;
    fact /= (2n * k + 2n) * (2n * k + 3n);
  }
}
const E = agree(e1, e2, 'e');

// √2 — integer sqrt vs Newton on the reciprocal check
const r2 = isqrt(2n * S * S);
const r2b = (r2 * r2 <= 2n * S * S && (r2 + 1n) * (r2 + 1n) > 2n * S * S) ? r2 : -1n;
const SQRT2 = agree(r2, r2b, 'sqrt2');

// φ — (1 + √5)/2 vs checking φ² = φ + 1 within rounding
const phi1 = (S + isqrt(5n * S * S)) / 2n;
const lhs = (phi1 * phi1) / S;
const rhs = phi1 + S;
if ((lhs > rhs ? lhs - rhs : rhs - lhs) > 10n) { log('phi identity failed'); process.exit(1); }
const PHI = agree(phi1, phi1, 'phi (φ² = φ + 1 verified)');

// ln 2 — 2 atanh(1/3) vs 18 atanh(1/26) − 2 atanh(1/4801) + 8 atanh(1/8749)
const ln2a = 2n * atanhInv(3);
const ln2b = 18n * atanhInv(26) - 2n * atanhInv(4801) + 8n * atanhInv(8749);
const LN2 = agree(ln2a, ln2b, 'ln2');

// ζ(3) — Apéry series (5/2) Σ (−1)^{k+1} / (k³ C(2k,k)); checked against a 60-digit reference
let z = 0n;
{
  let t = S / 2n; // a_1 = 1/2
  for (let k = 1n; t !== 0n; k++) {
    z += k % 2n ? t : -t;
    const k1 = k + 1n;
    t = (t * k * k * k) / (2n * k1 * k1 * (2n * k1 - 1n));
  }
  z = (5n * z) / 2n;
}
const ZETA3 = toStr(z);
const Z_REF = '1.202056903159594285399738161511449990764986292340498881792271555341838205';
if (!ZETA3.startsWith(Z_REF.slice(0, 60))) { log('zeta(3) reference mismatch'); process.exit(1); }
log('zeta3: OK (Apéry series, matches 58-decimal reference)');

// γ — Brent–McMillan with n = 2^13 vs n = 3·2^11
function gamma(n, lnN) {
  const n2 = BigInt(n) * BigInt(n);
  let A = -lnN;
  let B = S;
  let U = A;
  let V = B;
  for (let k = 1n; ; k++) {
    B = (B * n2) / (k * k);
    A = ((A * n2) / k + B) / k;
    U += A;
    V += B;
    if (B === 0n && (A > -2n && A < 2n)) break;
    if (k > 40n * BigInt(n)) break;
  }
  return (U * S) / V;
}
const LN2v = ln2a;
const ln3 = LN2v + 2n * atanhInv(5);
const g1 = gamma(8192, 13n * LN2v);
log('gamma #1 done');
const g2 = gamma(6144, ln3 + 11n * LN2v);
const GAMMA = agree(g1, g2, 'gamma');

const out = `// Generated by scripts/gen-digits.mjs — ${D} decimals per constant (truncated), cross-checked
// with independent formulas (π: Machin/Takano, e: two series, ln 2: two atanh formulas,
// γ: Brent–McMillan with two n, ζ(3): Apéry series vs reference prefix). Do not edit.
export const DIGITS = {
  pi: '${PI}',
  e: '${E}',
  phi: '${PHI}',
  sqrt2: '${SQRT2}',
  ln2: '${LN2}',
  zeta3: '${ZETA3}',
  gamma: '${GAMMA}',
} as const;
`;
const dest = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'data', 'digits.ts');
await mkdir(dirname(dest), { recursive: true });
await writeFile(dest, out);
log(`written ${dest}`);
